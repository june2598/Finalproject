  CREATE OR REPLACE FORCE EDITIONABLE VIEW "C##PROJECT"."MKT_SEC_STK" ("MARKET_ID", "MARKET_NM", "SEC_ID", "SEC_CODE", "SEC_NM", "STK_ID", "STK_CODE", "STK_NM") AS 
  SELECT 
    m.MARKET_ID,
    m.MARKET_NM,
    sec.SEC_ID,
    sec.SEC_CODE,
    sec.SEC_NM,
    s.STK_ID,
    s.STK_CODE,
    s.STK_NM
